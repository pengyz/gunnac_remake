-- 弹网格 24 槽（自机 20 ∪ 敌弹 12 = distinct 24；arena-midboss §1.1 交叠裁定）
local SHOT_SLOTS = {}
do
  local groups = { {0x80, 0x85}, {0x9C, 0xA1}, {0xB8, 0xBD}, {0xD4, 0xD9} }
  local seen = {}
  for _, g in ipairs(groups) do
    for y = g[1], g[2] do
      if not seen[y] then
        seen[y] = true
        SHOT_SLOTS[#SHOT_SLOTS + 1] = y
      end
    end
  end
  table.sort(SHOT_SLOTS)
end

-- 形 → 框组（左,右,上,下 × count；A 级框表解码，见文件头）
local BOX_BY_FORM = {
  [0x02] = { { -2, 2, -4, 4 } },
  [0x0B] = { { -4, 4, -4, 4 } },
  [0x21] = { { -2, 2, -6, 6 } },
  [0x22] = { { -6, 6, -2, 2 } },
  [0x28] = { { -4, 4, -4, 4 } },
  [0x0C] = { { -7, 7, -7, 7 } },
  [0x33] = { { -12, 12, -8, 8 }, { -8, 8, -12, 12 } },
}
local BOX_DEFAULT = { { -10, 10, -10, 10 } }   -- 未知形保守占位（显式，不发明表值）

-- 中 boss / boss 目标型码集合（状态转移表 bank14:$D86B：$4A→$4A 恒等、$5F→$17、$17→$17 自环）
local TARGET_TYPES = { [0x4A] = true, [0x5F] = true, [0x17] = true }

-- ---------------- 工具
local function clamp(v, lo, hi)
  if v < lo then return lo end
  if v > hi then return hi end
  return v
end

local function bit_test(val, bit)
  return math.floor(val / (2 ^ bit)) % 2 == 1
end

local function form_boxes(form)
  return BOX_BY_FORM[form] or BOX_DEFAULT
end

-- 对象 → 绝对框列表 {l,r,t,b}
local function obj_boxes(x, y, form, expand)
  expand = expand or 0
  local out = {}
  for _, o in ipairs(form_boxes(form)) do
    out[#out + 1] = {
      l = x + o[1] - expand, r = x + o[2] + expand,
      t = y + o[3] - expand, b = y + o[4] + expand,
    }
  end
  return out
end

local function boxes_overlap(a, b)
  return not (a.r < b.l or b.r < a.l or a.b < b.t or b.b < a.t)
end

-- 框到框距离（正=分离距离，负=侵入深度近似）
local function box_dist(p, b)
  local dx = 0
  if p.r < b.l then dx = b.l - p.r elseif b.r < p.l then dx = p.l - b.r end
  local dy = 0
  if p.b < b.t then dy = b.t - p.b elseif b.b < p.t then dy = p.t - b.b end
  if dx == 0 and dy == 0 then
    local ox = math.min(p.r, b.r) - math.max(p.l, b.l)
    local oy = math.min(p.b, b.b) - math.max(p.t, b.t)
    return -math.min(ox, oy)
  end
  return math.sqrt(dx * dx + dy * dy)
end

-- ---------------- 事件日志（逐发归因数据源）
local evPath = PLAN.out_dir .. "/" .. PLAN.name .. ".events.jsonl"
local evF = nil
local evN = 0
local function ev(kind, frame, fields)
  if not evF then evF = io.open(evPath, "w") end
  if not evF or evN > 400000 then return end
  evN = evN + 1
  local parts = { string.format('"f":%d,"kind":"%s"', frame, kind) }
  for k, v in pairs(fields or {}) do
    if type(v) == "string" then
      parts[#parts + 1] = string.format('"%s":"%s"', k, v)
    else
      parts[#parts + 1] = string.format('"%s":%s', k, tostring(v))
    end
  end
  evF:write("{" .. table.concat(parts, ",") .. "}\n")
  if evN % 256 == 0 then evF:flush() end
end

-- ---------------- 逐帧按键录制（record-to-scenario 输入面）
local inPath = PLAN.out_dir .. "/" .. PLAN.name .. ".inputs.jsonl"
local inF = io.open(inPath, "w")
local BTN_ORDER = { "a", "b", "start", "select", "up", "down", "left", "right" }
local function record_input(frame, btn)
  if not inF then return end
  local parts = {}
  for i = 1, #BTN_ORDER do
    local b = BTN_ORDER[i]
    parts[#parts + 1] = string.format('"%s":%s', b, btn[b] and "true" or "false")
  end
  inF:write(string.format('{"f":%d,%s}\n', frame, table.concat(parts, ",")))
  if frame % 256 == 0 then inF:flush() end
end
BOT.record_input = record_input

-- ---------------- 状态采集（判定时点 = inputPolled，读到的是上一帧终态）
local function capture(read)
  local s = {}
  s.pstate = read(0x0400)
  s.px = read(0x04E0)
  s.py = read(0x04FC)
  s.stage = read(0x0180)
  s.flags26 = read(0x0026)
  s.lives = read(0x018D)
  s.boss_type = read(0x041B)
  s.boss_x = read(0x04FB)
  s.boss_y = read(0x0517)
  s.boss_hp = read(0x064B)
  s.enemies = {}
  for n = 8, 27 do
    local t = read(0x0400 + n)
    if t ~= 0 then
      s.enemies[#s.enemies + 1] = {
        slot = n, type = t, x = read(0x04E0 + n), y = read(0x04FC + n),
        form = read(0x0518 + n), hp = read(0x0630 + n),
      }
    end
  end
  s.bullets = {}
  for _, yslot in ipairs(SHOT_SLOTS) do
    if read(0x040E + yslot) ~= 0 and read(0x063E + yslot) == 0x80 then
      s.bullets[#s.bullets + 1] = { x = read(0x04EE + yslot), y = read(0x055E + yslot), yslot = yslot }
    end
  end
  s.boss = nil
  for _, e in ipairs(s.enemies) do
    if TARGET_TYPES[e.type] then
      s.boss = e
      break
    end
  end
  -- HP 读点：目标 boss 槽 $0630+n（中 boss 实测槽 27 ⇒ $064B，arena-midboss §3.1）
  s.boss_hp = s.boss and read(0x0630 + s.boss.slot) or read(0x064B)
  return s
end

