-- tools/scenario_capture.lua —— S2 oracle 场景采集执行器（通用）
-- 由 tools/scenario_run.py 把 PLAN 表字面量前置后整拼为 analysis/_gen/<name>.lua 喂给 Mesen2 2.1.1。
-- DSL 语义只在 tools/scenario_run.py 解析（无第二套解析逻辑）；本文件只执行 PLAN。
--
-- API 依据（Mesen2 2.1.1 实测探针，见任务 t8/t12 记录）：
--   emu.addEventCallback(fn, "inputPolled"|"endFrame")  帧回调
--   emu.setInput({a=..,b=..,start=..,select=..,up=..,down=..,left=..,right=..}, 0)  注入按键
--   emu.read(address, memType)  读一字节（memType=内存类型枚举；RAM 见 MEMTYPE）
--   emu.takeScreenshot() -> png 字节串（需自行落盘）
--   emu.getState()  全机状态（cpu.pc/a/x/y/sp、ppu.*、mapper.*、frameCount）
--   emu.stop  停止模拟但**不退出进程** ⇒ 驱动看 DONE 标记后 SIGTERM
--
-- 帧计数约定（差分复现靠它锁死）：
--   frame 在 inputPolled 递增；schedule[frame] 的按键在该帧注入；
--   endFrame（帧 N 渲染完成后）写 trace 行 / 截图 / RAM dump；
--   frame >= PLAN.frames 或 bot 提前收机（BOT.wants_stop）写 DONE 并停机（task-105：
--   跳帧/分叉使 frame 越过 PLAN.frames 时旧 `==` 永不命中 ⇒ 不再写 trace、DONE 记录实际帧）。

local PLAN = PLAN or error("PLAN missing: must be generated by tools/scenario_run.py")

-- memType=8：CPU 总线视图（Mesen2 MemoryType 枚举值，t12 探针实测——mt 0..40 仅 8/9 非零；
-- B 级证据：f600 时 mt=8 读 $0002=FF、$0100 栈页=C1、$8000=A9（恰为 LDA# 操作码）、
-- RAM[0..63] 26 字节非零；mt=255 报 invalid memory type。勿凭猜测改）。
local MEMTYPE = PLAN.memtype or 8

local name = PLAN.name
local frames = PLAN.frames
local pressLen = PLAN.press_len or 2
local tracePath = PLAN.out_dir .. "/" .. name .. ".frames.jsonl"
local capPath = PLAN.out_dir .. "/" .. name .. ".captures.jsonl"
local donePath = PLAN.out_dir .. "/" .. name .. ".done"
local logPath = PLAN.out_dir .. "/" .. name .. ".lua.log"

local function log(s)
  local f = io.open(logPath, "a")
  if f then f:write(s .. "\n") f:close() end
end

-- task-145：脚本装载时刻的游戏 frameCount（取证 GUI 模式装载/注册相对开机相位差）。
-- 约定：`load_game_frame > 1` ⇒ 脚本在游戏已开机数帧后才装载（GUI 晚装模式，实测=3）⇒ 需相位对齐；
--           ≤1/nil ⇒ 脚本先于/同时开机装载（headless testRunner 实测=1），无需相位对齐（gate=0）。
local load_game_frame = nil
do
  local sok, st = pcall(emu.getState)
  local lfc = (sok and st) and (st.frameCount or nil) or nil
  if type(lfc) == "number" then load_game_frame = lfc end
  log("script load: game_frame=" .. tostring(lfc == nil and "?" or lfc))
end

local function hex2(n) return string.format("%02X", n) end

local function jstr(s)
  s = tostring(s):gsub("\\", "\\\\"):gsub('"', '\\"'):gsub("\n", "\\n"):gsub("\r", "\\r")
  return '"' .. s .. '"'
end

-- 帧计数与计数器：必须先于 saveShot/dumpRam 等闭包声明（Lua 词法作用域，
-- 声明在后的 local 不会被先前闭包捕获——t12 更正注）。
local frame = 0
local nTrace, nCap, nShot = 0, 0, 0
local doneWritten = false -- DONE 幂等（task-105：overshoot/bot_stop 后可能再来 endFrame）
local frameErrors = 0 -- 逐帧工作体 pcall 错误计数（task-105：错误不阻断 DONE）
local first_poll_fc = nil -- task-145：场景起始（首条计数帧）的游戏 frameCount

-- task-145 相位对齐：GUI 晚装模式下 inputPolled 回调注册发生在开机后的可变帧（随脚本大小/
-- 磁盘缓存变化）⇒ 首帧相对开机存在 ±N 帧偏移（跨脚本早期帧相位差根因）。对齐规则：仅当
-- `load_game_frame > 1`（GUI 晚装；headless testRunner 实测装载帧=1）时统一等到游戏
-- frameCount ≥ PHASE_ALIGN_FRAME 才开始计数/注入输入（跳过装载期已跑帧、不注入，不改变
-- 游戏状态）；headless 完全不变（装载帧=1 ⇒ 不对齐）。
local PHASE_ALIGN_FRAME = 7
local phase_align_checked = false
local phase_align_gate = nil

-- ---------------- 输入计划展开为逐帧按键表
local schedule = {}
local function addRange(a, b, btns)
  for f = a, b do
    local t = schedule[f]
    if not t then t = {} schedule[f] = t end
    for _, btn in ipairs(btns) do t[btn] = true end
  end
end
for _, e in ipairs(PLAN.holds) do addRange(e.from, e.to, e.buttons) end
for _, e in ipairs(PLAN.presses) do addRange(e.frame, e.frame + pressLen - 1, e.buttons) end

-- 采集点索引
local capAt = {}
for _, e in ipairs(PLAN.captures) do capAt[e.frame] = e.tag end
local everyN = PLAN.capture_every and PLAN.capture_every.n or 0
local everyTag = PLAN.capture_every and PLAN.capture_every.tag or "auto"

-- RAM 写注入计划（poke/poke_every 解析期展开；G-S5-6 触发注入取证）：
-- 帧 f inputPolled 时写 CPU 总线（memType=8）——与按键注入同一时序口径（schedule(N) 语义）。
-- 纪律注：注入=外部事件输入（同 gate_300 外部事件先例）；产出锚必须标注 trigger=injected。
local pokeAt = {}
local nPoke = 0
for _, e in ipairs(PLAN.pokes or {}) do
  local t = pokeAt[e.frame]
  if not t then t = {} pokeAt[e.frame] = t end
  t[#t + 1] = {tonumber(e.addr, 16), e.val}
  nPoke = nPoke + 1
end

-- ---------------- 内存读取
local function readByte(addr)
  local ok, v = pcall(emu.read, addr, MEMTYPE)
  if ok then return v end
  return 0
end

local function readRange(fromAddr, toAddr)
  local parts = {}
  for a = fromAddr, toAddr do parts[#parts + 1] = hex2(readByte(a)) end
  return table.concat(parts)
end

local function cpuJson()
  local st = emu.getState()
  return string.format('{"pc":%d,"a":%d,"x":%d,"y":%d,"sp":%d}',
    st["cpu.pc"], st["cpu.a"], st["cpu.x"], st["cpu.y"], st["cpu.sp"])
end

local function saveShot(tag)
  local ok, png = pcall(emu.takeScreenshot)
  if ok and type(png) == "string" then
    local p = string.format("%s/%s_f%05d_%s.png", PLAN.shots_dir, name, frame, tag)
    local f = io.open(p, "wb")
    if f then f:write(png) f:close() return p end
  end
  log("takeScreenshot failed at frame " .. frame)
  return nil
end

local function dumpRam(tag)
  local p = string.format("%s/%s_f%05d_%s.ram.hex", PLAN.out_dir, name, frame, tag)
  local f = io.open(p, "w")
  if f then f:write(readRange(0x0000, 0x07FF) .. "\n") f:close() return p end
  return nil
end

-- ---------------- 回调注册
local traceF = assert(io.open(tracePath, "w"))
local capF = assert(io.open(capPath, "w"))

-- W-NEW 行缓冲 NMI 级插桩（t94）：probe_mem 访存 PC 轨迹（观察性，不改行为）
-- 【2026-10-20 修复·probe 非变址存储写点盲区（l5-0160 G1）】旧实现
-- `emu.addMemoryCallback(fn, "write", lo, hi)` 传**字符串**"write"：Mesen2 2.1.1 把它静默
-- 转成整数 0 = emu.callbackType.read ⇒ 实际注册的是**读回调**（且兜底 `emu.memCallbackType`
-- 在 2.1.1 根本不存在，恒落回同一个字符串）。后果：非变址存储（STA/STX abs/zp）写循环
-- 永不触发（$0160 全部 ROM 写点零事件）；"变址写"事件实为存储指令的**假读**（dummy read，
-- 如 STA $161,Y 假读落在未进位的 $0160）；RMW 只出读相位旧值。
-- 诊断证据：analysis/tmp/probe_cb_diag.jsonl（str_write≡str_read≡enum_read≡num_0；
-- callbackType 实测={read=0,write=1,exec=2}；enum_write 抓到 STA $7FE/$7FF/$E9/$180 直写族）。
-- 现按实测枚举**双流注册**（写流=新增 setter/清零可见面，读流=保留读侧 1:1 对账口径），
-- 事件行新增 "op":"r"/"w" 字段。**只改捕获面，不改输入/行为**。
-- 注：Mesen2 2.1.1 Lua 无 addBreakPoint API（emu.addBreakPoint=nil），l5-0160 §6 G1 建议的
-- "addBreakPoint 写断点"绕行法不可用 ⇒ 本修复是唯一可用补法（详见 probe-setter-blindspot-fix.md）。
if PLAN.probe_mem and #PLAN.probe_mem > 0 then
  local probePath = PLAN.out_dir .. "/" .. name .. ".probe.jsonl"
  local probeF = io.open(probePath, "w")
  local probeN = 0
  local function probeLog(addr, val, op)
    if probeN > 3000000 then return end
    probeN = probeN + 1
    local ok, st = pcall(emu.getState)
    -- 2026-10-14 修复：Mesen2 getState 为扁平键（st["cpu.pc"]），旧代码读 st.cpu.pc 恒得 "????"；
    -- 同时补 x/y/a 寄存器（识别 STA $400,X / $401,Y 等变址写点的实际索引）。
    local cpu = (ok and st) and st or {}
    local pc = cpu["cpu.pc"] and string.format("%04X", cpu["cpu.pc"]) or "????"
    local xr = cpu["cpu.x"] or -1
    local yr = cpu["cpu.y"] or -1
    local ar = cpu["cpu.a"] or -1
    local fc = (ok and st) and (st.frameCount or 0) or 0
    probeF:write(string.format('{"f":%d,"pc":"%s","a":"%04X","v":%d,"x":%d,"y":%d,"ar":%d,"op":"%s"}\n',
      fc, pc, addr, val, xr, yr, ar, op))
    if probeN % 512 == 0 then probeF:flush() end
  end
  -- Mesen2 2.1.1 实测枚举 emu.callbackType={read=0,write=1,exec=2}；表缺失时用实测数值兜底。
  -- **禁止**用字符串类型参数（"write" 会被静默当 read=0，即本次修的坑）。
  local CB = emu.callbackType or {}
  local WTYPE = CB.write or 1
  local RTYPE = CB.read or 0
  for _, r in ipairs(PLAN.probe_mem) do
    local lo, hi = tonumber(r[1], 16), tonumber(r[2], 16)
    for _, s in ipairs({{"w", WTYPE}, {"r", RTYPE}}) do
      local op, ctype = s[1], s[2]
      local ok = pcall(emu.addMemoryCallback, function(address, value)
        probeLog(address, value, op)
      end, ctype, lo, hi)
      probeF:write(string.format('{"probe":"%04X-%04X","op":"%s","ctype":%d,"cb":%s}\n',
        lo, hi, op, ctype, tostring(ok)))
      probeF:flush()
    end
  end
  emu.addEventCallback(function() probeF:flush() end, "endFrame")
end

-- DONE 收尾（task-105）：endFrame 主路径 + inputPolled 兜底共用；幂等。
-- overshoot=跳帧/分叉使 frame 越过 PLAN.frames；DONE 记实际帧与计划帧。
local function finalize(bot_stop, why)
  if doneWritten then return end
  doneWritten = true
  pcall(function() traceF:flush() traceF:close() end)
  pcall(function() capF:flush() capF:close() end)
  local overshoot = frame > frames
  if overshoot then
    log("scenario overshoot(" .. tostring(why) .. "): frame=" .. frame .. " plan=" .. frames
      .. "（跳帧/分叉；trace 停在实际渲染帧，DONE 记实际帧）")
  end
  local d = io.open(donePath, "w")
  if d then
    d:write(string.format(
      '{"frames":%d,"frames_plan":%d,"frames_actual":%d,"overshoot":%s,"trace_lines":%d,"captures":%d,"shots":%d,"bot_stop":%s,"finalize_by":%s,"frame_errors":%d}\n',
      frame, frames, frame, overshoot and "true" or "false", nTrace, nCap, nShot,
      bot_stop and "true" or "false", jstr(why), frameErrors))
    d:close()
  end
  log("scenario done at frame " .. frame .. " (plan " .. frames .. ")"
    .. (overshoot and " (overshoot)" or "") .. (bot_stop and " (bot stop)" or "")
    .. " finalize_by=" .. tostring(why))
  pcall(emu.stop)
end

emu.addEventCallback(function()
  -- task-145 相位对齐（见上）：晚装模式统一对齐到游戏帧 PHASE_ALIGN_FRAME 起点。
  if not phase_align_checked then
    phase_align_checked = true
    if load_game_frame and load_game_frame > 1 then
      phase_align_gate = PHASE_ALIGN_FRAME
      log("phase align: late-load mode (script_load_game_frame=" .. tostring(load_game_frame)
        .. "), align_gate=" .. tostring(PHASE_ALIGN_FRAME))
    else
      phase_align_gate = 0
    end
  end
  if phase_align_gate and phase_align_gate > 0 then
    local sok, st = pcall(emu.getState)
    local gfc = (sok and st) and (st.frameCount or 0) or 0
    if gfc < phase_align_gate then return end
  end
  frame = frame + 1
  if frame == 1 then
    local sok, st = pcall(emu.getState)
    first_poll_fc = (sok and st) and (st.frameCount or -1) or -1
    log("scenario start: game_frame=" .. tostring(first_poll_fc)
      .. " align_gate=" .. tostring(phase_align_gate))
  end
  -- task-105 韧性：单帧异常（bot 决策/录制/poke）不得中断收尾——逐帧工作体全 pcall，
  -- 错误计数进 DONE；终止判定（inputPolled 兜底）始终执行。
  local ok, err = pcall(function()
    -- B2 v4 bot 闭环：帧 ≥ PLAN.bot.from 起由决策器（tools/tas_bot.lua）实时决策按键；
    -- 前缀帧沿用 schedule。逐帧按键录制（inputs.jsonl）→ tas_gen record-to-scenario 开环回放。
    local btn
    if PLAN.bot and BOT and frame >= PLAN.bot.from then
      btn = BOT.decide(frame, readByte) or {}
    else
      btn = schedule[frame] or {}
    end
    pcall(emu.setInput, btn, 0)
    if PLAN.bot and BOT and BOT.record_input then
      BOT.record_input(frame, btn)
    end
    local pk = pokeAt[frame]
    if pk then
      for _, p in ipairs(pk) do
        local wok = pcall(emu.write, p[1], p[2], MEMTYPE)
        local back = readByte(p[1])
        log(string.format("poke f%d $%04X:=%02X ok=%s readback=%02X",
          frame, p[1], p[2], tostring(wok), back))
      end
    end
  end)
  if not ok then
    frameErrors = frameErrors + 1
    log("inputPolled error at frame " .. frame .. ": " .. tostring(err))
  end
  -- task-105 兜底：若渲染帧被跳过、endFrame 不再回调，inputPolled 越过计划帧时也必须收尾
  if frame > frames and not doneWritten then finalize(false, "inputPolled-overshoot") end
end, "inputPolled")

emu.addEventCallback(function()
  if frame < 1 or doneWritten then return end

  -- 计划帧内：逐帧状态向量/采集/bot 观察。overshoot 帧（frame > frames，跳帧/分叉）不写 trace，
  -- 以免帧号断裂/超出计划行数；只做收尾逻辑（task-105）。逐帧工作体 pcall：
  -- 单帧异常（如 BOT.on_frame 在长 bot 场景末尾抛错）不得阻断 DONE 收尾。
  local ok, err = pcall(function()
    if frame <= frames then
      -- 逐帧状态向量
      local wparts = {}
      for _, w in ipairs(PLAN.watch) do
        wparts[#wparts + 1] = jstr(w.label) .. ":" .. readByte(tonumber(w.addr, 16))
      end
      for _, r in ipairs(PLAN.watch_ranges) do
        wparts[#wparts + 1] = jstr(r.label) .. ':"' .. readRange(tonumber(r.from, 16), tonumber(r.to, 16)) .. '"'
      end
      local line = '{"f":' .. frame .. ',"w":{' .. table.concat(wparts, ",") .. "}"
      if PLAN.ramframe then
        line = line .. ',"ram":"' .. readRange(0x0000, 0x07FF) .. '"'
      end
      traceF:write(line .. "}\n")
      nTrace = nTrace + 1

      -- 采集点（显式 tag 或 capture_every）
      local tag = capAt[frame]
      if not tag and everyN > 0 and frame % everyN == 0 then tag = everyTag end
      if tag then
        local shot = saveShot(tag)
        local ram = dumpRam(tag)
        capF:write(string.format('{"f":%d,"tag":%s,"shot":%s,"ram":%s,"cpu":%s}\n',
          frame, jstr(tag), shot and jstr(shot) or "null", ram and jstr(ram) or "null", cpuJson()))
        nCap = nCap + 1
        nShot = nShot + (shot and 1 or 0)
        capF:flush()
      end

      -- B2 v4：逐发归因观察钩子（只读：弹出生/消失 × 框相交 × HP 差分）
      if PLAN.bot and BOT and BOT.on_frame then
        BOT.on_frame(frame, readByte)
      end

      if frame % 120 == 0 then traceF:flush() end
    end
  end)
  if not ok then
    frameErrors = frameErrors + 1
    log("endFrame error at frame " .. frame .. ": " .. tostring(err))
  end

  -- 收尾（task-105 修复）：`frame >= frames` 或 bot 提前收机 ⇒ finalize 写 DONE 并停机。
  -- 旧条件 `frame == frames` 在跳帧/分叉（frame 越过 frames）时永不命中 ⇒ 驱动无 DONE 卡死；
  -- 且旧实现 DONE 前若逐帧工作抛错同样卡死（C3 旧快照现象）⇒ 现在终止判定在 pcall 之外恒执行。
  local bot_stop = false
  if PLAN.bot and BOT and BOT.wants_stop then
    local sok, sres = pcall(BOT.wants_stop, frame)
    bot_stop = (sok and sres) and true or false
    if not sok then
      log("wants_stop error at frame " .. frame .. ": " .. tostring(sres))
    end
  end
  if frame >= frames or bot_stop then
    finalize(bot_stop, "endFrame")
  end
end, "endFrame")

log(string.format("scenario %s started: frames=%d press_len=%d watch=%d ranges=%d ramframe=%s pokes=%d",
  name, frames, pressLen, #PLAN.watch, #PLAN.watch_ranges, tostring(PLAN.ramframe), nPoke))
